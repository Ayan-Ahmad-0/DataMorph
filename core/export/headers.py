"""Shared header comment and safe identifier/filename generators."""

from __future__ import annotations

import re
from pathlib import PurePosixPath
from typing import Iterable, List, Optional

DATAMORPH_VERSION = "1.0.0"


def sanitize_identifier(name: Optional[str], fallback: str = "dataset") -> str:
    """Convert an arbitrary filename or table name into a safe lowercase snake_case identifier."""
    if not name:
        return fallback
    base = sanitize_source_basename(name) or name
    stem = PurePosixPath(base).stem if "." in base else base
    cleaned = re.sub(r"[^A-Za-z0-9_]+", "_", stem).strip("_").lower()
    if not cleaned:
        return fallback
    if cleaned[0].isdigit():
        cleaned = f"t_{cleaned}"
    return cleaned[:64]


def sanitize_source_basename(dataset_name: Optional[str]) -> Optional[str]:
    """Return only the sanitized basename of a dataset name so local paths never leak."""
    if not dataset_name:
        return None
    normalized = dataset_name.replace("\x00", "").replace("\\", "/").strip()
    if not normalized:
        return None
    base = PurePosixPath(normalized).name
    if not base or base in (".", ".."):
        return None
    return re.sub(r"[\r\n]", "", base)


def build_export_header(
    *,
    target: str,
    job_id: str,
    timestamp_iso: str,
    dialect: Optional[str] = None,
    dataset_name: Optional[str] = None,
    caveats: Optional[Iterable[str]] = None,
    comment_prefix: str = "-- ",
) -> str:
    """Build a deterministic, secret-free header block for exported files."""
    lines: List[str] = [
        f"{comment_prefix}Generated by DataMorph v{DATAMORPH_VERSION}",
        f"{comment_prefix}Recipe / Job ID: {job_id}",
        f"{comment_prefix}Target: {target}" + (f" | Dialect: {dialect}" if dialect else ""),
    ]
    safe_source = sanitize_source_basename(dataset_name)
    if safe_source:
        lines.append(f"{comment_prefix}Source Dataset: {safe_source}")
    lines.append(f"{comment_prefix}Generated At (UTC): {timestamp_iso}")

    if caveats:
        caveat_list = [c.strip() for c in caveats if c and c.strip()]
        if caveat_list:
            lines.append(f"{comment_prefix}Notes:")
            for item in caveat_list:
                lines.append(f"{comment_prefix}  - {item}")

    return "\n".join(lines)

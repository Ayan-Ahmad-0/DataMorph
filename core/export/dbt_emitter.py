"""dbt model (.sql) and schema.yml emitter derived from RecipeIR and assertions."""

from __future__ import annotations

import re
from typing import Any, Dict, List

from core.export.base import EmitterOutput
from core.export.headers import build_export_header, sanitize_identifier
from core.export.ir import RecipeIR
from core.export.models import ExportOptions, ExportedFile
from core.export.sql_emitter import SqlEmitter

_YAML_SAFE_BARE_RE = re.compile(r"^[A-Za-z0-9_.\-]+$")


def _yaml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    if _YAML_SAFE_BARE_RE.match(text) and text.lower() not in ("true", "false", "null", "yes", "no", "on", "off"):
        return text
    escaped = text.replace("'", "''")
    return f"'{escaped}'"


def _resolve_dbt_names(options: ExportOptions) -> tuple[str, str, str]:
    """Return (source_schema, source_table, model_name) safely sanitized."""
    if options.source_name and "." in options.source_name:
        schema_part, table_part = options.source_name.split(".", 1)
        src_schema = sanitize_identifier(schema_part, fallback="raw")
        src_table = sanitize_identifier(table_part, fallback="dataset")
    elif options.source_name:
        src_schema = "raw"
        src_table = sanitize_identifier(options.source_name, fallback="dataset")
    else:
        src_schema = "raw"
        src_table = sanitize_identifier(options.dataset_name, fallback="dataset")

    model_base = sanitize_identifier(options.dataset_name or src_table, fallback="dataset")
    model_name = model_base if model_base.startswith("cleaned_") else f"cleaned_{model_base}"
    return src_schema, src_table, model_name


def _render_schema_yml(
    ir: RecipeIR,
    *,
    model_name: str,
    options: ExportOptions,
) -> tuple[str, List[str]]:
    warnings: List[str] = []
    header = build_export_header(
        target="dbt-schema",
        job_id=options.job_id,
        timestamp_iso=options.utc_timestamp_iso(),
        dialect=options.dialect,
        dataset_name=options.dataset_name,
        comment_prefix="# ",
    )

    lines: List[str] = [
        header,
        "",
        "version: 2",
        "",
        "models:",
        f"  - name: {_yaml_scalar(model_name)}",
        "    description: \"Cleaned dataset generated by DataMorph\"",
    ]

    if not options.include_tests:
        return "\n".join(lines) + "\n", warnings

    # Collect model-level tests (composite dedupe keys) and per-column tests
    model_tests: List[Dict[str, Any]] = []
    col_tests: Dict[str, List[Any]] = {}
    uses_dbt_utils = False

    for assertion in ir.assertions:
        if assertion.kind == "unique_combination":
            uses_dbt_utils = True
            model_tests.append(
                {
                    "dbt_utils.unique_combination_of_columns": {
                        "combination_of_columns": assertion.columns
                    }
                }
            )
        elif assertion.kind == "unique":
            col = assertion.columns[0]
            tests = col_tests.setdefault(col, [])
            if "unique" not in tests:
                tests.append("unique")
        elif assertion.kind == "not_null":
            col = assertion.columns[0]
            tests = col_tests.setdefault(col, [])
            if "not_null" not in tests:
                tests.append("not_null")
        elif assertion.kind == "accepted_range":
            uses_dbt_utils = True
            col = assertion.columns[0]
            tests = col_tests.setdefault(col, [])
            tests.append({"dbt_utils.accepted_range": dict(assertion.params)})

    if model_tests:
        lines.append("    tests:")
        for test in model_tests:
            for test_name, params in test.items():
                lines.append(f"      - {test_name}:")
                cols_list = ", ".join(_yaml_scalar(c) for c in params["combination_of_columns"])
                lines.append(f"          combination_of_columns: [{cols_list}]")

    if col_tests:
        lines.append("    columns:")
        for col in ir.columns:
            tests = col_tests.get(col)
            if not tests:
                continue
            lines.append(f"      - name: {_yaml_scalar(col)}")
            lines.append("        tests:")
            for item in tests:
                if isinstance(item, str):
                    lines.append(f"          - {item}")
                elif isinstance(item, dict):
                    for test_name, params in item.items():
                        lines.append(f"          - {test_name}:")
                        for k, v in params.items():
                            lines.append(f"              {k}: {_yaml_scalar(v)}")

    if uses_dbt_utils:
        warnings.append(
            "schema.yml includes dbt_utils tests (dbt_utils.accepted_range / "
            "unique_combination_of_columns); ensure dbt-labs/dbt_utils is in packages.yml."
        )

    return "\n".join(lines) + "\n", warnings


class DbtEmitter:
    """Emits a dbt SQL model and schema.yml test definition."""

    name: str = "dbt"
    file_extension: str = ".sql"

    def __init__(self) -> None:
        self._sql_emitter = SqlEmitter()

    def emit(self, ir: RecipeIR, options: ExportOptions) -> EmitterOutput:
        src_schema, src_table, model_name = _resolve_dbt_names(options)
        source_jinja = f"{{{{ source('{src_schema}', '{src_table}') }}}}"

        sql_out = self._sql_emitter.emit_with_source(
            ir,
            options,
            source_token=source_jinja,
            filename=f"{model_name}.sql",
            target_label="dbt",
        )

        # Wrap dbt config block right after header comment
        sql_file = sql_out.files[0]
        parts = sql_file.content.split("\n\n", 1)
        if len(parts) == 2:
            model_content = f"{parts[0]}\n\n{{{{ config(materialized='table') }}}}\n\n{parts[1]}"
        else:
            model_content = f"{{{{ config(materialized='table') }}}}\n\n{sql_file.content}"

        schema_content, schema_warnings = _render_schema_yml(
            ir,
            model_name=model_name,
            options=options,
        )

        all_warnings = list(sql_out.warnings)
        for w in schema_warnings:
            if w not in all_warnings:
                all_warnings.append(w)

        return EmitterOutput(
            files=[
                ExportedFile(name=f"{model_name}.sql", content=model_content, language="sql"),
                ExportedFile(name="schema.yml", content=schema_content, language="yaml"),
            ],
            warnings=all_warnings,
        )

// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import * as api from '../../lib/api';
import { ExportCodeModal } from './ExportCodeModal';
import { ResultsPage } from '../../pages/ResultsPage';

vi.mock('../../components/privacy/PiiShieldCard', () => ({
  PiiShieldCard: () => null,
}));

vi.mock('../../components/wrangler/DataWranglerGrid', () => ({
  DataWranglerGrid: () => null,
}));

vi.mock('../../components/explore/SqlQueryBox', () => ({
  SqlQueryBox: () => null,
}));

vi.mock('../../components/connectors/ConnectorModal', () => ({
  ConnectorModal: () => null,
}));

vi.mock('../../lib/api', async () => {
  const actual = await vi.importActual<typeof import('../../lib/api')>('../../lib/api');
  return {
    ...actual,
    exportJobAsCode: vi.fn(),
    downloadExportedCodeZip: vi.fn(),
  };
});

const sqlResponse: api.ExportCodeResponse = {
  target: 'sql',
  dialect: 'duckdb',
  files: [
    {
      name: 'clean.sql',
      language: 'sql',
      content: "-- Generated by DataMorph\nWITH staged AS (\n  SELECT * FROM {{ source_table }}\n)\nSELECT * FROM staged;",
    },
  ],
  warnings: [],
};

const dbtResponse: api.ExportCodeResponse = {
  target: 'dbt',
  dialect: 'snowflake',
  files: [
    {
      name: 'cleaned_orders.sql',
      language: 'sql',
      content: "SELECT * FROM {{ source('raw', 'orders') }}",
    },
    {
      name: 'schema.yml',
      language: 'yaml',
      content: "version: 2\nmodels:\n  - name: cleaned_orders",
    },
  ],
  warnings: ['Title-case edge cases may differ on apostrophes.'],
};

const pandasResponse: api.ExportCodeResponse = {
  target: 'pandas',
  dialect: null,
  files: [
    {
      name: 'clean_pandas.py',
      language: 'python',
      content: 'import pandas as pd\n\ndef clean(df: pd.DataFrame) -> pd.DataFrame:\n    return df\n',
    },
  ],
  warnings: ['pandas casts invalid numeric strings to NaN.'],
};

describe('ExportCodeModal', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    (api.exportJobAsCode as ReturnType<typeof vi.fn>).mockResolvedValue(sqlResponse);
    (api.downloadExportedCodeZip as ReturnType<typeof vi.fn>).mockResolvedValue(undefined);
    Object.defineProperty(window.URL, 'createObjectURL', {
      writable: true,
      value: vi.fn(() => 'blob:mock-url'),
    });
    Object.defineProperty(window.URL, 'revokeObjectURL', {
      writable: true,
      value: vi.fn(),
    });
  });

  afterEach(() => {
    cleanup();
  });

  it('opens from ResultsPage Export as Code button and loads SQL preview', async () => {
    const jobData: api.JobDetailResponse = {
      job: {
        id: 'job_123',
        filename: 'orders.csv',
        status: 'DONE',
        progress_pct: 100,
        current_stage: 'Done',
        file_size_bytes: 1024,
        row_count: 10,
        privacy_mode: false,
      },
      recipe_plain_english: [],
      open_questions: [],
      download_urls: {},
      verification: {
        comparison: {
          rows_before: 10,
          rows_after: 10,
          duplicates_before: 0,
          duplicates_after: 0,
          rows_delta: '0',
        },
        test_results: [],
      },
    };

    render(<ResultsPage jobData={jobData} onRestart={vi.fn()} />);

    const triggerBtn = screen.getByRole('button', { name: /Export as Code/i });
    fireEvent.click(triggerBtn);

    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledWith('job_123', {
        target: 'sql',
        dialect: 'duckdb',
      });
    });

    expect(screen.getByRole('dialog')).toBeInTheDocument();
    expect(screen.getAllByText('clean.sql').length).toBeGreaterThan(0);
    const pre = document.querySelector('pre');
    expect(pre?.textContent).toContain('WITH staged AS');
  });

  it('re-fetches when target, dialect, and tests toggle change and hides irrelevant controls', async () => {
    (api.exportJobAsCode as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce(sqlResponse)
      .mockResolvedValueOnce(dbtResponse)
      .mockResolvedValueOnce({ ...dbtResponse, dialect: 'bigquery' })
      .mockResolvedValueOnce({ ...dbtResponse, dialect: 'bigquery' })
      .mockResolvedValueOnce(pandasResponse);

    render(
      <ExportCodeModal
        isOpen={true}
        jobId="job_abc"
        datasetName="orders.csv"
        onClose={vi.fn()}
      />,
    );

    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledWith('job_abc', {
        target: 'sql',
        dialect: 'duckdb',
      });
    });

    // Dialect is shown for SQL; dbt tests toggle is hidden
    expect(screen.getByLabelText('Dialect')).toBeInTheDocument();
    expect(screen.queryByText('Include data quality tests')).not.toBeInTheDocument();

    // Switch to dbt
    fireEvent.click(screen.getByRole('button', { name: 'dbt' }));
    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledWith('job_abc', {
        target: 'dbt',
        dialect: 'duckdb',
        include_tests: true,
      });
    });

    // Change dialect to BigQuery
    fireEvent.change(screen.getByLabelText('Dialect'), { target: { value: 'bigquery' } });
    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledWith('job_abc', {
        target: 'dbt',
        dialect: 'bigquery',
        include_tests: true,
      });
    });

    // Toggle data quality tests off
    const testsSwitch = screen.getByRole('switch');
    fireEvent.click(testsSwitch);
    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledWith('job_abc', {
        target: 'dbt',
        dialect: 'bigquery',
        include_tests: false,
      });
    });

    // Switch to pandas: both dialect and tests toggle hide
    fireEvent.click(screen.getByRole('button', { name: 'pandas' }));
    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledWith('job_abc', {
        target: 'pandas',
      });
    });
    expect(screen.queryByLabelText('Dialect')).not.toBeInTheDocument();
    expect(screen.queryByText('Include data quality tests')).not.toBeInTheDocument();
  });

  it('switches file tabs, renders warnings callout, copies code, and downloads zip for dbt', async () => {
    (api.exportJobAsCode as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce(sqlResponse)
      .mockResolvedValueOnce(dbtResponse);

    render(
      <ExportCodeModal
        isOpen={true}
        jobId="job_dbt"
        datasetName="orders.csv"
        onClose={vi.fn()}
      />,
    );

    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledTimes(1);
    });

    fireEvent.click(screen.getByRole('button', { name: 'dbt' }));

    await waitFor(() => {
      expect(screen.getByRole('tab', { name: 'cleaned_orders.sql' })).toBeInTheDocument();
      expect(screen.getByRole('tab', { name: 'schema.yml' })).toBeInTheDocument();
    });

    // Warnings callout rendered
    expect(screen.getByText('Compatibility notices')).toBeInTheDocument();
    expect(screen.getByText('Title-case edge cases may differ on apostrophes.')).toBeInTheDocument();

    // Switch to schema.yml tab
    fireEvent.click(screen.getByRole('tab', { name: 'schema.yml' }));
    await waitFor(() => {
      const pre = document.querySelector('pre');
      expect(pre?.textContent).toContain('version: 2');
    });

    // Copy active file (schema.yml)
    fireEvent.click(screen.getByRole('button', { name: /^Copy$/i }));
    await waitFor(() => {
      expect(navigator.clipboard.writeText).toHaveBeenCalledWith(dbtResponse.files[1].content);
      expect(screen.getByRole('button', { name: /Copied/i })).toBeInTheDocument();
    });

    // Multi-file dbt uses zip download API
    fireEvent.click(screen.getByRole('button', { name: /Download \(\.zip\)/i }));
    await waitFor(() => {
      expect(api.downloadExportedCodeZip).toHaveBeenCalledWith(
        'job_dbt',
        { target: 'dbt', dialect: 'duckdb', include_tests: true },
        'datamorph_export_dbt.zip',
      );
    });
  });

  it('downloads single-file targets locally via Blob', async () => {
    render(
      <ExportCodeModal
        isOpen={true}
        jobId="job_single"
        onClose={vi.fn()}
      />,
    );

    await waitFor(() => {
      expect(screen.getAllByText('clean.sql').length).toBeGreaterThan(0);
    });

    const clickSpy = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {});
    fireEvent.click(screen.getByRole('button', { name: /^Download$/i }));

    expect(window.URL.createObjectURL).toHaveBeenCalledTimes(1);
    expect(clickSpy).toHaveBeenCalledTimes(1);
    expect(window.URL.revokeObjectURL).toHaveBeenCalledWith('blob:mock-url');
    clickSpy.mockRestore();
  });

  it('shows error callout on failure and recovers via Retry button', async () => {
    (api.exportJobAsCode as ReturnType<typeof vi.fn>)
      .mockRejectedValueOnce(new Error('Recipe must be verified before export.'))
      .mockResolvedValueOnce(sqlResponse);

    render(
      <ExportCodeModal
        isOpen={true}
        jobId="job_err"
        onClose={vi.fn()}
      />,
    );

    await waitFor(() => {
      expect(screen.getByText('Failed to generate code')).toBeInTheDocument();
      expect(screen.getByText('Recipe must be verified before export.')).toBeInTheDocument();
    });

    fireEvent.click(screen.getByRole('button', { name: /Retry/i }));

    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledTimes(2);
      expect(screen.getAllByText('clean.sql').length).toBeGreaterThan(0);
    });
  });

  it('passes source_name when entered and closes on Close button or Escape', async () => {
    const onClose = vi.fn();
    render(
      <ExportCodeModal
        isOpen={true}
        jobId="job_src"
        onClose={onClose}
      />,
    );

    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenCalledTimes(1);
    });

    fireEvent.change(screen.getByLabelText('Source table'), {
      target: { value: 'raw.orders' },
    });

    await waitFor(() => {
      expect(api.exportJobAsCode).toHaveBeenLastCalledWith('job_src', {
        target: 'sql',
        dialect: 'duckdb',
        source_name: 'raw.orders',
      });
    });

    fireEvent.keyDown(window, { key: 'Escape' });
    expect(onClose).toHaveBeenCalledTimes(1);

    fireEvent.click(screen.getByRole('button', { name: /^Close$/i }));
    expect(onClose).toHaveBeenCalledTimes(2);
  });
});
